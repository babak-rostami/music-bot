<?php

namespace App\Services\Payment\Contracts;

use App\Models\Payment;

/**
 * بعد از تأیید موفق یه پرداخت صدا زده میشه
 * کاری که باید انجام بشه رو انجام میده
 * هر نوع (اشتراک، یا هر محصول دیگه‌ای در آینده) یه پیاده‌سازی جدا از این داره
 * این لایه اجازه میده سرویس پرداخت اصلاً ندونه بعد از verify
 * شدن یه پرداخت، دقیقاً چه اتفاقی باید بیفته.
 */
interface PayableFulfillerInterface
{
    /**
     * بعد از تأیید قطعی یه پرداخت صدا زده میشه.
     * اگر به هر دلیلی دوبار صدا زده بشه (مثلاً دو درخواست موازی)، دوبار کاری انجام نده.
     */
    public function fulfill(Payment $payment): void;
}
